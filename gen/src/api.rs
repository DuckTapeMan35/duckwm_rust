use std::collections::HashMap;
use std::fmt::Write;

use prost_types::field_descriptor_proto::{Label, Type};
use prost_types::{DescriptorProto, FieldDescriptorProto, FileDescriptorSet};

/// Commands with a typed method written by hand in client.rs.
const HAND_WRITTEN: &[&str] = &["get_keybinds", "get_workspace_states"];

pub fn generate(fds: &FileDescriptorSet) -> String {
    let file = &fds.file[0];
    let messages: HashMap<&str, &DescriptorProto> =
        file.message_type.iter().map(|m| (m.name(), m)).collect();
    let command = messages["Command"];

    let mut out = String::from(
        "// Generated by gen/ from duckwm.proto. Do not edit.\n\n\
         use crate::proto;\n\
         use crate::{Client, Cmd, Result, Value};\n\n\
         impl Client {\n",
    );
    for variant in &command.field {
        let name = variant.name();
        if HAND_WRITTEN.contains(&name) {
            continue;
        }
        let msg_name = short(variant.type_name());
        let msg = messages[msg_name];
        let params: Vec<String> = msg
            .field
            .iter()
            .map(|f| format!("{}: {}", ident(f.name()), param_type(f)))
            .collect();
        let inits: Vec<String> = msg
            .field
            .iter()
            .map(|f| {
                let (name, value) = (ident(f.name()), convert(f));
                if name == value {
                    name
                } else {
                    format!("{name}: {value}")
                }
            })
            .collect();
        let payload = if inits.is_empty() {
            format!("proto::{msg_name} {{}}")
        } else {
            format!("proto::{msg_name} {{ {} }}", inits.join(", "))
        };
        let self_arg = std::iter::once("&mut self".to_string())
            .chain(params)
            .collect::<Vec<_>>();
        writeln!(out, "    /// Run `{name}` on its own.").unwrap();
        writeln!(
            out,
            "    pub fn {}({}) -> Result<Value> {{",
            ident(name),
            self_arg.join(", ")
        )
        .unwrap();
        writeln!(out, "        self.run_one(Cmd::{}({payload}))", camel(name)).unwrap();
        writeln!(out, "    }}\n").unwrap();
    }
    out.truncate(out.trim_end().len());
    out.push_str("\n}\n");
    out
}

/// ".duckwm.v1.Focus" -> "Focus".
fn short(type_name: &str) -> &str {
    type_name.rsplit('.').next().unwrap()
}

fn repeated(f: &FieldDescriptorProto) -> bool {
    f.label() == Label::Repeated
}

fn optional(f: &FieldDescriptorProto) -> bool {
    f.proto3_optional()
}

/// The scalar's Rust type, as prost generates it.
fn scalar(f: &FieldDescriptorProto) -> String {
    match f.r#type() {
        Type::Double => "f64".into(),
        Type::Float => "f32".into(),
        Type::Int64 | Type::Sint64 | Type::Sfixed64 => "i64".into(),
        Type::Uint64 | Type::Fixed64 => "u64".into(),
        Type::Int32 | Type::Sint32 | Type::Sfixed32 => "i32".into(),
        Type::Uint32 | Type::Fixed32 => "u32".into(),
        Type::Bool => "bool".into(),
        Type::String => "&str".into(),
        Type::Bytes => "&[u8]".into(),
        Type::Enum | Type::Message => format!("proto::{}", short(f.type_name())),
        Type::Group => unreachable!("proto2 groups"),
    }
}

/// What the method takes for this field: borrowed where prost owns.
fn param_type(f: &FieldDescriptorProto) -> String {
    let t = scalar(f);
    if repeated(f) {
        match f.r#type() {
            Type::Message => format!("Vec<{t}>"),
            _ => format!("&[{t}]"),
        }
    } else if optional(f) {
        format!("Option<{t}>")
    } else {
        t
    }
}

/// The expression turning the parameter into prost's field.
fn convert(f: &FieldDescriptorProto) -> String {
    let v = ident(f.name());
    match (f.r#type(), repeated(f), optional(f)) {
        (Type::String, true, _) => format!("{v}.iter().map(|s| s.to_string()).collect()"),
        (Type::Bytes, true, _) => format!("{v}.iter().map(|b| b.to_vec()).collect()"),
        (Type::Enum, true, _) => format!("{v}.iter().map(|e| *e as i32).collect()"),
        (Type::Message, true, _) => v,
        (_, true, _) => format!("{v}.to_vec()"),
        (Type::String, _, true) => format!("{v}.map(str::to_owned)"),
        (Type::Bytes, _, true) => format!("{v}.map(<[u8]>::to_vec)"),
        (Type::Enum, _, true) => format!("{v}.map(|e| e as i32)"),
        (Type::Message, _, true) => v,
        (Type::String, _, false) => format!("{v}.to_owned()"),
        (Type::Bytes, _, false) => format!("{v}.to_vec()"),
        (Type::Enum, _, false) => format!("{v} as i32"),
        // A singular message is an Option in prost; the method makes it required.
        (Type::Message, _, false) => format!("Some({v})"),
        _ => v,
    }
}

/// snake_case -> UpperCamelCase, as prost names oneof variants.
fn camel(s: &str) -> String {
    s.split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// A field or method name, raw if it's a Rust keyword.
fn ident(s: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn",
        "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
        "return", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
        "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
        "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
    ];
    if KEYWORDS.contains(&s) {
        format!("r#{s}")
    } else {
        s.to_string()
    }
}
